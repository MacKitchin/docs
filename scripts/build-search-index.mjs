#!/usr/bin/env node

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sourceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(sourceRoot, "search-data.js");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if ([".git", ".mintlify", "node_modules"].includes(entry.name)) continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(fullPath)));
    if (entry.isFile() && entry.name.endsWith(".mdx")) files.push(fullPath);
  }
  return files;
}

function cleanValue(value = "") {
  return value.trim().replace(/^['"]|['"]$/g, "");
}

function parseFrontmatter(source) {
  const match = source.match(/^---\s*\n([\s\S]*?)\n---\s*\n?/);
  if (!match) return { attributes: {}, body: source };

  const attributes = {};
  for (const line of match[1].split("\n")) {
    const field = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (field) attributes[field[1]] = cleanValue(field[2]);
  }
  return { attributes, body: source.slice(match[0].length) };
}

function plainText(source) {
  return source
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ")
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[{}*_`>#|]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function headings(source) {
  return [...source.matchAll(/^#{1,3}\s+(.+)$/gm)]
    .map((match) => plainText(match[1]))
    .filter(Boolean);
}

function routeFor(filePath) {
  const relative = path.relative(sourceRoot, filePath).replace(/\\/g, "/");
  const route = relative.replace(/\.mdx$/, "").replace(/\/index$/, "");
  return route === "index" ? "/" : `/${route}`;
}

function inferredTitle(filePath) {
  return path
    .basename(filePath, ".mdx")
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

const files = (await walk(sourceRoot)).sort();
const records = [];

for (const filePath of files) {
  const source = await readFile(filePath, "utf8");
  const { attributes, body } = parseFrontmatter(source);
  if (String(attributes.noindex).toLowerCase() === "true") continue;

  const bodyText = plainText(body);
  records.push({
    title: attributes.title || inferredTitle(filePath),
    sidebarTitle: attributes.sidebarTitle || "",
    description: attributes.description || bodyText.slice(0, 180),
    headings: headings(body).slice(0, 18),
    body: bodyText.slice(0, 6000),
    path: routeFor(filePath),
  });
}

const banner =
  "// Generated by scripts/build-search-index.mjs. Do not edit by hand.\n";
await writeFile(
  outputPath,
  `${banner}window.COMPANY_BRAIN_SEARCH_INDEX = ${JSON.stringify(records)};\n`,
  "utf8",
);

console.log(`Wrote ${records.length} searchable pages to ${outputPath}`);
